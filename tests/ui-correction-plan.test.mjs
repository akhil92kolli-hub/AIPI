const luminance = (hex) => {
  const rgb = hex.match(/[a-f\d]{2}/gi).map((value) => Number.parseInt(value, 16) / 255).map((value) => value <= 0.04045 ? value / 12.92 : ((value + 0.055) / 1.055) ** 2.4);
  return 0.2126 * rgb[0] + 0.7152 * rgb[1] + 0.0722 * rgb[2];
};
const contrast = (foreground, background) => {
  const values = [luminance(foreground), luminance(background)].sort((a, b) => b - a);
  return (values[0] + 0.05) / (values[1] + 0.05);
};
assert.ok(contrast("f0eeee", "181818") >= 4.5, "dark K Maps route contrast must meet WCAG AA");
assert.ok(contrast("15212b", "ffffff") >= 4.5, "light K Maps route contrast must meet WCAG AA");

