import assert from 'node:assert/strict';
import { commerceState } from '../fixtures/workspace-commerce/state.mjs';
import { saveWorkspaceGroup, workspaceTargets, reviewWorkspaceRelationship } from '../packages/core/workspace-groups.mjs';
import { bindTaskWorkspace } from '../packages/core/task-workspace.mjs';
import { buildTaskContext } from '../packages/core/task-context.mjs';
import { createTaskHandoff } from '../packages/core/handoff.mjs';

const state = commerceState();
saveWorkspaceGroup(state, {name:'Commerce', projectIds:['storefront','orders']}, 'wsg_commerce');
bindTaskWorkspace(state);
const [front, orders] = state.projects;
const targets = workspaceTargets(state, 'wsg_commerce');
const from = targets.find(t => t.ref.projectId === front.id && t.kind === 'page');
const to = targets.find(t => t.ref.projectId === orders.id && t.kind === 'component');
const input = {fromKey:from.key, toKey:to.key, type:'CALLS', status:'approved', evidence:'Reviewed caller and handler.', reviewer:'Reviewer'};
const review = reviewWorkspaceRelationship(state, 'wsg_commerce', input);
const task = {id:'finding', title:'Investigate missing consumer', artifactIds:[to.ref.entityId], contextSelectionMode:'manual'};
orders.tasks.push(task);
let context = buildTaskContext(orders, task.id);
assert.equal(context.reviewedRelationships.length, 1);
assert.equal(context.reviewedRelationships[0].from.ref.projectId, 'storefront');
assert.equal(context.reviewedRelationships[0].runtimeVerified, false);
assert.equal(context.workspace, undefined, 'Evidence does not expand task verification scope');
let handoff = createTaskHandoff({project:orders, task, context});
assert.match(handoff.markdown, /Reviewed relationship/);
assert.equal(handoff.handoff.reviewedRelationships[0].id, review.id);
task.contextControls = {[to.ref.entityId]:'exclude'};
assert.equal(buildTaskContext(orders, task.id).reviewedRelationships.length, 0);
task.contextControls = {};
orders.sourceContext.lastScannedAt = 'changed';
assert.equal(buildTaskContext(orders, task.id).reviewedRelationships.length, 0, 'Stale reviews are excluded');
reviewWorkspaceRelationship(state, 'wsg_commerce', {...input, status:'rejected', expectedVersion:1});
assert.equal(buildTaskContext(orders, task.id).reviewedRelationships.length, 0, 'Rejected reviews are excluded');
console.log('Finding context includes only current approved explicitly linked cross-repository evidence');
