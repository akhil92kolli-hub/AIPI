import assert from 'node:assert/strict';
import { commerceState } from '../fixtures/workspace-commerce/state.mjs';
import { saveWorkspaceGroup, workspaceTargets, reviewWorkspaceRelationship, relationshipReviews, getWorkspaceTarget } from '../packages/core/workspace-groups.mjs';
const state = commerceState();
const group = saveWorkspaceGroup(state,{name:'Commerce',projectIds:state.projects.map(p=>p.id)},'wsg_commerce');
const targets = workspaceTargets(state,group.id);
const from = targets.find(t=>t.ref.projectId==='storefront' && t.kind==='page');
const to = targets.find(t=>t.ref.projectId==='orders' && t.kind==='api');
const input = {fromKey:from.key,toKey:to.key,type:'CALLS',status:'approved',evidence:'Reviewed checkout page caller and orders handler source references.',reviewer:'Fixture reviewer'};
assert.ok(!getWorkspaceTarget(state,group.id,from.key).related.some(t=>t.key===to.key));
const review = reviewWorkspaceRelationship(state,group.id,input);
assert.equal(review.runtimeVerified,false);
assert.equal(getWorkspaceTarget(state,group.id,from.key).related.find(t=>t.key===to.key).relationshipReviewId,review.id);
assert.throws(()=>reviewWorkspaceRelationship(state,group.id,input),/changed/);
assert.throws(()=>reviewWorkspaceRelationship(state,group.id,{...input,fromKey:'missing'}),/available/);
state.projects.find(p=>p.id==='orders').sourceContext.lastScannedAt='new-revision';
assert.equal(relationshipReviews(state,group.id)[0].stale,true);
assert.ok(!getWorkspaceTarget(state,group.id,from.key).related.some(t=>t.key===to.key));
reviewWorkspaceRelationship(state,group.id,{...input,expectedVersion:1,status:'rejected'});
assert.equal(state.relationshipReviewHistory.length,1);
assert.equal(relationshipReviews(state,group.id)[0].stale,false);
assert.ok(!getWorkspaceTarget(state,group.id,from.key).related.some(t=>t.key===to.key));
state.workspaceGroups.find(g=>g.id===group.id).projectIds=['storefront'];
assert.equal(relationshipReviews(state,group.id)[0].stale,true);
state.workspaceGroups.find(g=>g.id===group.id).projectIds=['storefront','orders'];
state.projects.find(p=>p.id==='orders').sourceContext.gitRevision='commit_initial';
const gitReview = reviewWorkspaceRelationship(state,group.id,{...input,expectedVersion:2,status:'approved'});
assert.equal(gitReview.version,3);
assert.equal(relationshipReviews(state,group.id)[0].stale,false);
state.projects.find(p=>p.id==='orders').sourceContext.lastScannedAt='ephemeral-rescan-timestamp';
assert.equal(relationshipReviews(state,group.id)[0].stale,false, 'ephemeral rescan does not invalidate review when git revision and files are unchanged');
state.projects.find(p=>p.id==='orders').sourceContext.gitRevision='commit_next';
assert.equal(relationshipReviews(state,group.id)[0].stale,true, 'git revision change invalidates review');
console.log('Reviewed relationships: ownership, explicit approval, rejection, history, conflicts, stale source, git revision stability and membership passed');
