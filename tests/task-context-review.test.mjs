import assert from "node:assert/strict";
import { commerceState } from "../fixtures/workspace-commerce/state.mjs";
import { taskArtifacts } from "../packages/core/task-context.mjs";
import { prepareTaskDraftContext, submitTaskContextReview } from "../packages/core/task-context-review.mjs";
const project = commerceState().projects.find(p => p.id === "storefront");
const artifact = taskArtifacts(project)[0];
const input = { draft_id: "draft", objective: "Improve checkout", artifact_ids: [artifact.id], acceptance_criteria: ["Keyboard navigation works"] };
const review = prepareTaskDraftContext(project, input);
assert.equal(review.references[0].id, artifact.id);
assert.deepEqual(review.acceptanceCriteria, input.acceptance_criteria);
assert.equal(prepareTaskDraftContext(project, input).reviewId, review.reviewId);
assert.equal(project.taskContextReviews.length, 1);
assert.notEqual(prepareTaskDraftContext(project, { ...input, objective: "Different goal" }).reviewId, review.reviewId);
assert.throws(() => prepareTaskDraftContext(project, { ...input, contract_ids: ["foreign"] }), /unavailable/);
assert.throws(() => submitTaskContextReview(project, { review_id: "unknown", summary: "test" }), /unavailable/);
assert.throws(() => submitTaskContextReview(project, { review_id: review.reviewId, summary: "test", artifact_ids: ["foreign"] }), /unavailable/);
submitTaskContextReview(project, { review_id: review.reviewId, summary: "Review this component", artifact_ids: [artifact.id], acceptance_criteria: ["Error message is accessible"] });
assert.equal(project.taskContextReviews[0].suggestions.references[0].id, artifact.id);
assert.equal(project.tasks?.length ?? 0, 0, "review never creates or modifies a task");
assert.deepEqual(project.taskContextReviews[0].acceptanceCriteria, input.acceptance_criteria, "suggestions never overwrite manual criteria");
console.log("Task draft context: identity, manual inputs, validated suggestions, isolation and non-creation passed");
