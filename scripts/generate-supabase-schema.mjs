import fs from "node:fs/promises";
import path from "node:path";

const root = path.resolve(import.meta.dirname, "..");
const migrationsDirectory = path.join(root, "supabase", "migrations");
const files = (await fs.readdir(migrationsDirectory)).filter((file) => file.endsWith(".sql")).sort();
const sections = await Promise.all(files.map(async (file) => `-- migration: ${file}\n${(await fs.readFile(path.join(migrationsDirectory, file), "utf8")).trim()}\n`));
const header = "-- GENERATED FILE: fresh database bootstrap only.\n-- supabase/migrations/*.sql are authoritative; do not edit this file directly.\n-- Regenerate with: npm run schema:generate\n\n";
await fs.writeFile(path.join(root, "supabase", "schema.sql"), `${header}${sections.join("\n")}`);
console.log(`Generated supabase/schema.sql from ${files.length} migrations.`);
